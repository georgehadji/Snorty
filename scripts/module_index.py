"""Write docs/modules.md: one row per snorty package, built from the code so it cannot drift.

Purpose is the package docstring, the rule columns come from pyproject.toml, and the test count
from the files under tests/ that name the package. Run: uv run python scripts/module_index.py
"""

import ast
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("docs") / "modules.md"
# packages whose spec is named after its V1 module id rather than the package
SPEC_NAMES = {
    "core": "alert-core",
    "snort": "snort-adapter",
    "lab": "rule-lab",
    "journal": "vault-journal",
    "wireshark": "packets",
}
HEADER = """# Snorty packages

Generated by `scripts/module_index.py` from the code; do not edit. Run
`uv run python scripts/module_index.py` after adding, removing or redescribing a package.

- **Purpose:** the package docstring.
- **Tests:** files under `tests/` that name the package.
- **Processes:** `yes` when the import-linter `subprocess` contract does not cover the package.
- **Strict:** in the strict mypy override.
- **Independent:** in the import-linter independence contract (siblings never import it).

| Package | Purpose | Spec | Tests | Processes | Strict | Independent |
|---|---|---|---|---|---|---|
"""


def packages(root: Path) -> list[str]:
    src = root / "src" / "snorty"
    return sorted(p.name for p in src.iterdir() if (p / "__init__.py").is_file())


def purpose(root: Path, pkg: str) -> str:
    text = (root / "src" / "snorty" / pkg / "__init__.py").read_text(encoding="utf-8")
    doc = ast.get_docstring(ast.parse(text))
    if not doc:
        return "(no docstring)"
    return " ".join(doc.split("\n\n")[0].split()).replace("|", "\\|")


def spec(root: Path, pkg: str) -> str:
    name = f"SPEC-{SPEC_NAMES.get(pkg, pkg)}.md"
    return f"[{name}](../{name})" if (root / name).is_file() else "none"


def count_tests(root: Path, pkg: str) -> int:
    named = re.compile(rf"\bsnorty\.{re.escape(pkg)}\b")
    files = (root / "tests").rglob("*.py")
    return sum(1 for f in files if named.search(f.read_text(encoding="utf-8")))


def rules(root: Path) -> tuple[set[str], set[str], set[str]]:
    """(packages kept from subprocess, strict packages, independent packages)."""
    data = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    no_procs: set[str] = set()
    independent: set[str] = set()
    for c in data.get("tool", {}).get("importlinter", {}).get("contracts", []):
        if c.get("forbidden_modules") == ["subprocess"]:
            no_procs.update(c["source_modules"])
        if c.get("type") == "independence":
            independent.update(c["modules"])
    strict = {
        m.removesuffix(".*")
        for o in data.get("tool", {}).get("mypy", {}).get("overrides", [])
        if o.get("strict")
        for m in o["module"]
    }
    return no_procs, strict, independent


def render(root: Path) -> str:
    no_procs, strict, independent = rules(root)

    def mark(pkg: str, group: set[str]) -> str:
        return "yes" if f"snorty.{pkg}" in group else "no"

    rows = [
        f"| `{p}` | {purpose(root, p)} | {spec(root, p)} | {count_tests(root, p)} "
        f"| {'no' if f'snorty.{p}' in no_procs else 'yes'} | {mark(p, strict)} "
        f"| {mark(p, independent)} |\n"
        for p in packages(root)
    ]
    return HEADER + "".join(rows)


def main() -> int:
    out = ROOT / OUT
    out.parent.mkdir(exist_ok=True)
    out.write_text(render(ROOT), encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
